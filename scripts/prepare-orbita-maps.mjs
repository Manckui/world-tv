// Run with the Natural Earth countries and Openpolis Italian regions GeoJSON
// paths. The UI only downloads these small, preprocessed files, never a map SDK.
import { readFile, writeFile } from "node:fs/promises";
import { geoArea, geoCentroid } from "d3-geo";

function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const [ax, ay] = points[0];
  const [bx, by] = points.at(-1);
  const length = (bx - ax) ** 2 + (by - ay) ** 2;
  let best = 0, index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const [x, y] = points[i];
    const t = length ? Math.max(0, Math.min(1, ((x - ax) * (bx - ax) + (y - ay) * (by - ay)) / length)) : 0;
    const distance = (x - ax - t * (bx - ax)) ** 2 + (y - ay - t * (by - ay)) ** 2;
    if (distance > best) { best = distance; index = i; }
  }
  return best > tolerance ** 2
    ? [...simplify(points.slice(0, index + 1), tolerance).slice(0, -1), ...simplify(points.slice(index), tolerance)]
    : [points[0], points.at(-1)];
}

function geometry(source, tolerance) {
  const polygons = source.type === "Polygon" ? [source.coordinates] : source.coordinates;
  const coordinates = polygons.map(polygon => {
    const rings = polygon.map(ring => simplify(ring, tolerance).map(point => point.map(n => +n.toFixed(4))));
    if (rings[0].length < 4) return null;
    // d3-geo expects clockwise exterior rings, unlike RFC 7946 GeoJSON.
    const valid = rings.filter(ring => ring.length >= 4);
    if (geoArea({ type: "Polygon", coordinates: valid }) > Math.PI * 2) valid.forEach(ring => ring.reverse());
    return valid;
  }).filter(Boolean);
  return { type: "MultiPolygon", coordinates };
}

const [worldPath, italyPath] = process.argv.slice(2);
if (!worldPath || !italyPath) throw new Error("Usage: node scripts/prepare-orbita-maps.mjs <countries.geojson> <regions.geojson>");
const world = JSON.parse(await readFile(worldPath, "utf8"));
const italy = JSON.parse(await readFile(italyPath, "utf8"));
world.features = world.features.map(feature => ({
  type: "Feature",
  properties: { code: feature.properties.ADM0_A3, name: feature.properties.NAME },
  geometry: geometry(feature.geometry, .08),
})).filter(feature => feature.geometry.coordinates.length);
italy.features = italy.features.map(feature => ({
  type: "Feature",
  properties: { code: feature.properties.reg_iso_3166_2, name: feature.properties.reg_name },
  geometry: geometry(feature.geometry, .009),
}));
const regions = italy.features.map(feature => ({
  ...feature.properties,
  center: geoCentroid(feature).map(n => +n.toFixed(4)),
})).sort((a, b) => a.name.localeCompare(b.name, "it"));
await writeFile("public/maps/world.json", JSON.stringify({ type: "FeatureCollection", features: world.features }));
await writeFile("public/maps/italy.json", JSON.stringify({ type: "FeatureCollection", features: italy.features }));
await writeFile("src/lib/orbita-regions.ts", `// Generated by scripts/prepare-orbita-maps.mjs; coordinates are [longitude, latitude].\nexport const REGIONS = ${JSON.stringify(regions, null, 2)} as const;\n`);
console.log(`Prepared ${world.features.length} countries and ${regions.length} Italian regions.`);
